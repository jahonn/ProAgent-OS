#!/usr/bin/env python3
"""Regenerate the checked-in mock demo recording.

Writes two views of one offline session:

  docs/demo.cast   asciinema v2 (play with `asciinema play docs/demo.cast`)
  docs/demo.svg    SMIL terminal animation for the README

From a checkout with the package installed (`pip install -e .`):

    python scripts/record_demo.py

The child processes force PROAGENT_LLM_PROVIDER=mock, drop provider
credentials and proxies, and use a temporary SQLite file. Nothing under
data/ is written, and no API key is read. Identifiers change on every
recording; the stage text does not.

The session is three beats: scripts/demo.py, a short
scripts/demo_support_desk.py beat, then scripts/demo_ops_incident.py.

Lines longer than the terminal width are wrapped on spaces (continuation
rows keep the original indent). The words are still the scripts' stdout.
That keeps `asciinema play` and the README frame readable.

Do not commit the temporary database. docs/demo.cast and docs/demo.svg
are the only artifacts.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAST_PATH = ROOT / "docs" / "demo.cast"
SVG_PATH = ROOT / "docs" / "demo.svg"

# Wide enough for a README column. Longer stdout lines wrap on spaces.
COLS = 100
ROWS = 25
FONT_PX = 14
LINE_PX = 21
MONO = "ui-monospace, SFMono-Regular, Menlo, Consolas, Liberation Mono, DejaVu Sans Mono, monospace"
# Monospace advance used only to size the SVG. A little wider than 0.62em so the
# last column is not clipped when the viewer's font is slightly wider than Menlo.
CHAR_PX = FONT_PX * 0.66
HOLD_MS = 4200

# Phrases the live scripts must print. If a future change drops one, re-record
# fails instead of publishing a demo that no longer matches the product.
REQUIRED_MARKERS = (
    "=== ProAgent OS Demo ===",
    "pk_demo_acme_analytics",
    "Acme Analytics Platform Overview",
    "sample_notes",
    "conversion rate",
    "status=completed",
    "['researcher', 'analyst']",
    "Conversion below 2.5% target",
    "executor noop, ok=True",
    "conversion_lift_pp",
    "market_scan",
    "_Generated by MockLLM for offline demo._",
    "=== ProAgent OS Support Desk Demo ===",
    "pk_demo_northwind_support",
    "ticket_triage",
    "Refund Policy",
    "Follow up: refund request matches the 30-day policy",
    "followups_reviewed",
    "Not a production helpdesk.",
    "=== ProAgent OS Ops Incident Demo ===",
    "pk_demo_harborline_oncall",
    "API 5xx Runbook",
    "Page on-call: API 5xx runbook matches",
    "nobody is paged",
    "Not a production incident system.",
)

_DROPPED_ENV = (
    "PROAGENT_LLM_API_KEY",
    "OPENAI_API_KEY",
    "PROAGENT_EXECUTOR_WEBHOOK_TOKEN",
    "PROAGENT_EXECUTOR_WEBHOOK_URL",
    "PROAGENT_ADMIN_KEY",
    "HTTP_PROXY",
    "HTTPS_PROXY",
    "ALL_PROXY",
    "http_proxy",
    "https_proxy",
    "all_proxy",
)

FILL = {
    "cmd": "#e6edf3",
    "banner": "#79c0ff",
    "good": "#3fb950",
    "stage": "#e6edf3",
    "json": "#8b949e",
    "text": "#c9d1d9",
    "blank": "#e6edf3",
}
PROMPT_FILL = "#3fb950"


@dataclass(frozen=True)
class Visual:
    text: str
    appear_ms: int
    kind: str
    source_index: int


def child_env(db_path: Path) -> dict[str, str]:
    """Environment for one demo process. Mock provider, no credentials."""
    env = os.environ.copy()
    for key in _DROPPED_ENV:
        env.pop(key, None)
    env["PROAGENT_LLM_PROVIDER"] = "mock"
    env["PROAGENT_EXECUTOR_MODE"] = "noop"
    env["PROAGENT_EXECUTOR_ON_APPROVE"] = "true"
    env["PROAGENT_KB_RETRIEVAL"] = "bm25"
    env["PROAGENT_DB_PATH"] = str(db_path)
    env["PYTHONUNBUFFERED"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    return env


def capture(script: Path, db_path: Path) -> str:
    proc = subprocess.run(
        [sys.executable, str(script)],
        cwd=ROOT,
        env=child_env(db_path),
        text=True,
        capture_output=True,
        check=False,
    )
    if proc.returncode != 0:
        raise SystemExit(
            f"{script.name} exited {proc.returncode}\n--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}"
        )
    if proc.stderr.strip():
        raise SystemExit(f"{script.name} wrote to stderr (recording aborted):\n{proc.stderr}")
    if not proc.stdout.strip():
        raise SystemExit(f"{script.name} produced no stdout")
    _assert_printable(proc.stdout, script.name)
    return proc.stdout


def _assert_printable(text: str, label: str) -> None:
    for index, ch in enumerate(text):
        if ch in "\n\r":
            continue
        if ord(ch) < 32 or ord(ch) == 127:
            raise SystemExit(f"{label} contains a control character at offset {index}")


def session_lines(demo_out: str, support_out: str, ops_out: str) -> list[str]:
    """Shell transcript: the three commands, then the bytes the scripts printed."""
    return [
        "$ export PROAGENT_LLM_PROVIDER=mock",
        "$ python scripts/demo.py",
        *demo_out.splitlines(),
        "",
        "$ python scripts/demo_support_desk.py",
        *support_out.splitlines(),
        "",
        "$ python scripts/demo_ops_incident.py",
        *ops_out.splitlines(),
        "",
    ]


def line_delay_ms(line: str) -> int:
    """How long to wait before revealing this line. JSON scrolls faster."""
    if line.startswith("$ export"):
        return 550
    if line.startswith("$ "):
        return 750
    if not line.strip():
        return 160
    if line.startswith("==="):
        return 520
    if line.startswith("[Dashboard]"):
        return 1400
    if line.startswith("Demo complete"):
        return 640
    if "Learning:" in line:
        return 780
    if line.startswith("[") and line[1:2].isdigit():
        return 440
    if _is_jsonish(line):
        return 36
    return 200


def _is_jsonish(line: str) -> bool:
    stripped = line.strip()
    if not stripped:
        return False
    return stripped[0] in "{[}]" or stripped[0] in "\"'"


def classify(line: str) -> str:
    if line.startswith("$ "):
        return "cmd"
    if line.startswith("==="):
        return "banner"
    if line.startswith("Demo complete"):
        return "good"
    if "status=completed" in line or "status → executed" in line:
        return "good"
    if line.startswith("[") and line[1:2].isdigit():
        return "stage"
    if _is_jsonish(line):
        return "json"
    if not line.strip():
        return "blank"
    return "text"


def soft_wrap(line: str, cols: int) -> list[str]:
    """Wrap on spaces. Continuations keep the source indent, or four spaces."""
    if cols < 8:
        raise ValueError("cols must be at least 8")
    if line == "" or len(line) <= cols:
        return [line]
    base_indent = line[: len(line) - len(line.lstrip(" "))]
    cont_indent = base_indent if base_indent else "    "
    if len(cont_indent) > cols // 2:
        cont_indent = cont_indent[: cols // 2]
    rows: list[str] = []
    remaining = line
    while remaining:
        if len(remaining) <= cols:
            rows.append(remaining)
            break
        floor = len(cont_indent) if rows else 0
        cut = remaining.rfind(" ", 0, cols + 1)
        if cut <= floor:
            cut = cols
            nxt = remaining[cut:]
        else:
            nxt = remaining[cut + 1 :]
        rows.append(remaining[:cut])
        if nxt and not nxt.startswith(cont_indent):
            nxt = cont_indent + nxt
        if nxt == remaining:
            raise ValueError(f"wrap made no progress on {line!r}")
        remaining = nxt
    return rows


def present(lines: list[str]) -> list[Visual]:
    """One visual row per wrapped line. A wrap continuation shares its parent's time."""
    visual: list[Visual] = []
    cursor = 0
    for source_index, line in enumerate(lines):
        kind = classify(line)
        parts = soft_wrap(line, COLS)
        for part_index, part in enumerate(parts):
            if part_index == 0 and source_index:
                cursor += line_delay_ms(line)
            if len(part) > COLS:
                raise SystemExit(f"wrapped row is {len(part)} columns (max {COLS}): {part!r}")
            visual.append(Visual(part, cursor, kind, source_index))
    return visual


def _poster_scroll(visual: list[Visual]) -> int:
    """Static frame: the mock demo from the command through the learning line.

    The playing animation still continues into the dashboard and the
    support-desk beat. If that opening does not fit, keep the learning
    line at the bottom of the window.
    """

    def find(pred, default: int = 0) -> int:
        for index, row in enumerate(visual):
            if pred(row):
                return index
        return default

    export_at = find(lambda row: row.text.startswith("$ export "))
    demo_at = find(lambda row: row.text.startswith("$ python scripts/demo.py"))
    learn_at = find(lambda row: "Learning:" in row.text, demo_at)
    while learn_at + 1 < len(visual) and visual[learn_at + 1].source_index == visual[learn_at].source_index:
        learn_at += 1
    for start in (export_at, demo_at):
        if learn_at - start + 1 <= ROWS:
            return start
    return max(0, learn_at - (ROWS - 1))


def _fmt_unit(value: float) -> str:
    if value <= 0:
        return "0"
    if value >= 1:
        return "1"
    return f"{value:.5f}".rstrip("0").rstrip(".")


def _xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_cast(visual: list[Visual]) -> str:
    if not visual:
        raise ValueError("empty session")
    total_s = (visual[-1].appear_ms + HOLD_MS) / 1000
    header = {
        "version": 2,
        "width": COLS,
        "height": ROWS,
        "timestamp": int(os.environ.get("SOURCE_DATE_EPOCH", "0") or "0") or _now(),
        "duration": round(total_s, 3),
        "title": "ProAgent OS mock demo",
        "env": {"SHELL": "/bin/bash", "TERM": "xterm-256color"},
        "theme": {
            "fg": "#e6edf3",
            "bg": "#0d1117",
            "palette": (
                "#0d1117:#ff7b72:#3fb950:#d29922:#79c0ff:#d2a8ff:#a5d6ff:#e6edf3:"
                "#6e7681:#ffa198:#56d364:#e3b341:#79c0ff:#d2a8ff:#b6e3ff:#ffffff"
            ),
        },
    }
    events: list[list[object]] = []
    for index, row in enumerate(visual):
        payload = _ansi(row.text, row.kind) + "\n"
        if index == 0:
            payload = "\x1b[2J\x1b[H\x1b[?25l" + payload
        events.append([round(row.appear_ms / 1000, 3), "o", payload])
    events.append([round(total_s, 3), "o", "\x1b[?25h"])
    body = [json.dumps(header, ensure_ascii=False, separators=(",", ":"))]
    body.extend(json.dumps(event, ensure_ascii=False, separators=(",", ":")) for event in events)
    return "\n".join(body) + "\n"


def _now() -> int:
    import time

    return int(time.time())


def _ansi(line: str, kind: str) -> str:
    if kind == "cmd" and line.startswith("$ "):
        return "\x1b[32m$\x1b[0m " + line[2:]
    if kind == "banner":
        return "\x1b[1;36m" + line + "\x1b[0m"
    if kind == "good":
        return "\x1b[32m" + line + "\x1b[0m"
    if kind == "json":
        return "\x1b[2m" + line + "\x1b[0m"
    return line


def build_svg(visual: list[Visual], total_ms: int) -> str:
    if not visual:
        raise ValueError("empty session")
    if total_ms <= 0:
        raise ValueError("duration must be positive")
    poster = _poster_scroll(visual)
    dur = f"{total_ms / 1000:.3f}s"
    pad_x = 18
    term_y = 44
    width = pad_x * 2 + round(COLS * CHAR_PX)
    height = term_y + ROWS * LINE_PX + 14
    inner_w = width - pad_x * 2
    inner_h = ROWS * LINE_PX

    scroll = _scroll_animation(visual, total_ms, dur)
    texts: list[str] = []
    for index, row in enumerate(visual):
        y = (index + 1) * LINE_PX - 5
        appear = _fmt_unit(row.appear_ms / total_ms)
        animate = ""
        if appear != "0":
            animate = (
                f'<animate attributeName="opacity" calcMode="discrete" '
                f'values="0;1;1" keyTimes="0;{appear};1" dur="{dur}" '
                f'repeatCount="indefinite"/>'
            )
        body = _text_body(row)
        texts.append(
            f'<text x="0" y="{y}" fill="{FILL[row.kind]}" opacity="1" xml:space="preserve">'
            f"{animate}{body}</text>"
        )

    title = "ProAgent OS — mock demo"
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img">\n'
        "<title>ProAgent OS mock demo</title>\n"
        "<desc>Offline recording of python scripts/demo.py, python scripts/demo_support_desk.py, "
        "and python scripts/demo_ops_incident.py with PROAGENT_LLM_PROVIDER=mock. "
        "Regenerated by python scripts/record_demo.py. No API key.</desc>\n"
        f'<rect width="{width}" height="{height}" rx="10" fill="#0d1117"/>\n'
        f'<rect width="{width}" height="36" rx="10" fill="#161b22"/>\n'
        f'<rect y="20" width="{width}" height="16" fill="#161b22"/>\n'
        '<circle cx="20" cy="18" r="6" fill="#ff5f57"/>\n'
        '<circle cx="40" cy="18" r="6" fill="#febc2e"/>\n'
        '<circle cx="60" cy="18" r="6" fill="#28c840"/>\n'
        f'<text x="{width / 2:.1f}" y="23" text-anchor="middle" fill="#8b949e" '
        f'font-family="{MONO}" font-size="13">{_xml(title)}</text>\n'
        f'<svg x="{pad_x}" y="{term_y}" width="{inner_w}" height="{inner_h}" overflow="hidden" '
        f'font-family="{MONO}" font-size="{FONT_PX}">\n'
        f'<g transform="translate(0 {-poster * LINE_PX})">\n'
        f"{scroll}\n"
        + "\n".join(texts)
        + "\n</g>\n</svg>\n</svg>\n"
    )


def _text_body(row: Visual) -> str:
    if row.kind == "cmd" and row.text.startswith("$ "):
        return f'<tspan fill="{PROMPT_FILL}">$</tspan><tspan fill="{FILL["cmd"]}">{_xml(row.text[1:])}</tspan>'
    return _xml(row.text)


def _scroll_animation(visual: list[Visual], total_ms: int, dur: str) -> str:
    frames: list[tuple[str, int]] = [("0", 0)]
    for index, row in enumerate(visual):
        rows = max(0, index - (ROWS - 1))
        stamp = _fmt_unit(row.appear_ms / total_ms)
        if rows != frames[-1][1]:
            if stamp == frames[-1][0]:
                frames[-1] = (stamp, rows)
            else:
                frames.append((stamp, rows))
    if frames[-1][0] != "1":
        frames.append(("1", frames[-1][1]))
    values = ";".join(f"0 {-rows * LINE_PX}" for _, rows in frames)
    key_times = ";".join(stamp for stamp, _ in frames)
    _assert_key_times(key_times, values)
    return (
        '<animateTransform attributeName="transform" type="translate" calcMode="discrete" '
        f'values="{values}" keyTimes="{key_times}" dur="{dur}" repeatCount="indefinite"/>'
    )


def _assert_key_times(key_times: str, values: str) -> None:
    stamps = key_times.split(";")
    parts = values.split(";")
    if len(stamps) != len(parts):
        raise SystemExit("scroll animation keyTimes and values differ in length")
    if stamps[0] != "0" or stamps[-1] != "1":
        raise SystemExit("scroll animation keyTimes must start at 0 and end at 1")
    nums = [float(item) for item in stamps]
    if any(b < a for a, b in zip(nums, nums[1:])):
        raise SystemExit("scroll animation keyTimes must be non-decreasing")


def cast_output(cast: str) -> str:
    """Concatenate stdout events. ANSI stays; callers that need plain text can strip it."""
    chunks: list[str] = []
    for line in cast.splitlines()[1:]:
        if not line.strip():
            continue
        event = json.loads(line)
        if event[1] == "o":
            chunks.append(event[2])
    return "".join(chunks)


def visible_text(text: str) -> str:
    """Drop ANSI and SVG tags, then collapse whitespace so wrapped markers still match."""
    no_ansi = re.sub(r"\x1b\[[0-9;?]*[A-Za-z]", "", text)
    no_tags = re.sub(r"<[^>]+>", " ", no_ansi)
    return re.sub(r"\s+", " ", no_tags)


def require_markers(text: str) -> None:
    visible = visible_text(text)
    missing = [marker for marker in REQUIRED_MARKERS if marker not in visible]
    if missing:
        raise SystemExit("recording is missing expected output:\n- " + "\n- ".join(missing))
    for forbidden in ("sk-", "PROAGENT_LLM_API_KEY", "BEGIN OPENAI", "/tmp/", "api.openai.com"):
        if forbidden in text or forbidden in visible:
            raise SystemExit(f"recording contains {forbidden!r}; aborting")


def window(visual: list[Visual], scroll: int) -> list[str]:
    return [row.text for row in visual[scroll : scroll + ROWS]]


def record() -> None:
    with tempfile.TemporaryDirectory(prefix="proagent-demo-") as tmp:
        root = Path(tmp)
        demo_out = capture(ROOT / "scripts" / "demo.py", root / "demo.db")
        support_out = capture(ROOT / "scripts" / "demo_support_desk.py", root / "support.db")
        ops_out = capture(ROOT / "scripts" / "demo_ops_incident.py", root / "ops.db")
    lines = session_lines(demo_out, support_out, ops_out)
    require_markers("\n".join(lines))
    visual = present(lines)
    total_ms = visual[-1].appear_ms + HOLD_MS
    cast = build_cast(visual)
    svg = build_svg(visual, total_ms)
    require_markers(cast_output(cast))
    require_markers(svg)
    # Wrapped SVG rows split long lines across elements. Check short anchors that
    # sit on their own line so a bad render still fails the generator.
    for anchor in (
        "=== ProAgent OS Demo ===",
        "=== ProAgent OS Support Desk Demo ===",
        "=== ProAgent OS Ops Incident Demo ===",
        "pk_demo_acme_analytics",
        "pk_demo_harborline_oncall",
    ):
        if anchor not in svg:
            raise SystemExit(f"svg is missing {anchor!r}")
    CAST_PATH.write_text(cast, encoding="utf-8")
    SVG_PATH.write_text(svg, encoding="utf-8")
    poster = _poster_scroll(visual)
    final = max(0, len(visual) - ROWS)
    print(f"Wrote {CAST_PATH.relative_to(ROOT)} ({len(cast)} bytes, {total_ms / 1000:.1f}s)")
    print(f"Wrote {SVG_PATH.relative_to(ROOT)} ({len(svg)} bytes, {len(visual)} rows)")
    print("\nStatic frame (shown if animation does not run):")
    print("\n".join(window(visual, poster)))
    print("\nFinal frame:")
    print("\n".join(window(visual, final)))


def main(argv: list[str] | None = None) -> None:
    args = list(sys.argv[1:] if argv is None else argv)
    if args:
        raise SystemExit(
            "usage: python scripts/record_demo.py\n\n"
            "Re-runs the mock demos and overwrites docs/demo.cast and docs/demo.svg."
        )
    record()


if __name__ == "__main__":
    main()
